import { describe, expect, it, vi } from "vitest";
import * as THREE from "three";
import { readFileSync } from "node:fs";
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js";
import { disposeBuiltScene, resolveModelSlot } from "../../src/scene/build";
import { ClipPlayer, clipsForClone, findClipPlayer, registerClipPlayer } from "../../src/scene/clipPlayback";
import type { ParsedTemplate } from "../../src/scene/cache";
import type { ModelSlot } from "../../src/scene/build";

describe("locked model playback", () => {
  it("plays a loaded animated and skinned GLB without changing the template", async () => {
    const data = readFileSync(new URL("../fixtures/skin-clip-morph.glb", import.meta.url));
    const bytes = Uint8Array.from(data);
    const gltf = await new GLTFLoader().parseAsync(bytes.buffer, "");
    const template = { scene: gltf.scene, meshes: [], animations: gltf.animations, dispose() {} } as ParsedTemplate;
    const clone = resolveModelSlot({ node: new THREE.Group(), asset: {} } as unknown as ModelSlot, template)[0];
    const player = new ClipPlayer(clone, gltf.animations);
    const animatedBone = clone.getObjectByName("bone1")!;
    const sourceBone = gltf.scene.getObjectByName("bone1")!;
    player.play(); player.update(0.5);
    expect(animatedBone.quaternion.equals(sourceBone.quaternion)).toBe(false);
    player.dispose();
  });
  it("rebinds UUID tracks for unnamed nodes without changing cached clips", () => {
    const scene = new THREE.Group();
    const unnamed = new THREE.Object3D(); scene.add(unnamed);
    const template = { scene, meshes: [], dispose() {} } as ParsedTemplate;
    const clone = resolveModelSlot({ node: new THREE.Group(), asset: {} } as unknown as ModelSlot, template)[0];
    const clip = new THREE.AnimationClip("unnamed", 1, [new THREE.NumberKeyframeTrack(`${unnamed.uuid}.position[x]`, [0, 1], [0, 2])]);
    const player = new ClipPlayer(clone, clipsForClone(scene, clone, [clip]));
    player.play(); player.update(0.5);
    expect(clone.children[0].position.x).toBeCloseTo(1);
    expect(unnamed.position.x).toBe(0);
    expect(clip.tracks[0].name).toBe(`${unnamed.uuid}.position[x]`);
    player.dispose();
  });
  it("rebinds skeletons and plays only the selected instance", () => {
    const scene = new THREE.Group();
    const bone = new THREE.Bone(); bone.name = "bone";
    const mesh = new THREE.SkinnedMesh(new THREE.BufferGeometry(), new THREE.MeshBasicMaterial());
    mesh.add(bone); mesh.bind(new THREE.Skeleton([bone])); scene.add(mesh);
    const template = { scene, meshes: [mesh], dispose() {} } as ParsedTemplate;
    const make = () => resolveModelSlot({ node: new THREE.Group(), asset: {} } as unknown as ModelSlot, template)[0];
    const first = make(); const second = make();
    const firstMesh = first.children[0] as THREE.SkinnedMesh;
    const secondMesh = second.children[0] as THREE.SkinnedMesh;
    expect(firstMesh.skeleton.bones[0]).not.toBe(bone);
    expect(firstMesh.skeleton.bones[0]).not.toBe(secondMesh.skeleton.bones[0]);
    expect(firstMesh.geometry).toBe(mesh.geometry);
    const clip = new THREE.AnimationClip("move", 1, [new THREE.NumberKeyframeTrack("bone.position[x]", [0, 1], [0, 2])]);
    const player = new ClipPlayer(first, [clip]); player.play(); player.update(0.5);
    expect(firstMesh.skeleton.bones[0].position.x).toBeCloseTo(1);
    expect(secondMesh.skeleton.bones[0].position.x).toBe(0);
    expect(bone.position.x).toBe(0);
    player.pause(); player.seek(0.25);
    expect(firstMesh.skeleton.bones[0].position.x).toBeCloseTo(0.5);
    expect(player.playing).toBe(false);
    const unregister = registerClipPlayer("source", "scene", "node", player);
    expect(findClipPlayer("source", "scene", "node")).toBe(player);
    unregister();
    expect(findClipPlayer("source", "scene", "node")).toBeUndefined();
    expect(player.playing).toBe(false);
    expect(player.mixer.existingAction(clip)).toBeNull();
    const disposeInstance = vi.spyOn(firstMesh.skeleton, "dispose");
    const disposeTemplate = vi.spyOn(mesh.skeleton, "dispose");
    const disposeGeometry = vi.spyOn(mesh.geometry, "dispose");
    const root = new THREE.Group(); root.add(first);
    disposeBuiltScene({ root, nodes: new Map(), modelSlots: [], materials: new Map() });
    expect(disposeInstance).toHaveBeenCalledOnce();
    expect(disposeTemplate).not.toHaveBeenCalled();
    expect(disposeGeometry).not.toHaveBeenCalled();
  });
});
