// scripts/build-desktop.mjs — bundle src/plugin.tsx into desktop/plugin.js.
//
// Contract (stage-0 §4.1, standalone-editor.md rules 7/17):
//   - ESM format, UNMINIFIED output (reviewers read the bundle).
//   - JSX via the automatic PRODUCTION runtime (react/jsx-runtime). The
//     dev runtime (react/jsx-dev-runtime) must not appear anywhere in the
//     output — the build fails if it does.
//   - Externalize ONLY @hermes/plugin-sdk, react, react/jsx-runtime.
//     Everything else (notably three.js) is bundled.
//   - CI size gate: 8 MiB (hard fail). Under 3.5 MiB is a target, not a gate
//     (warn only). The host loader cap is 16 MiB (working assumption, PR1
//     spike S1 confirms it on the pinned build).
//   - Regenerates desktop/THIRD_PARTY_NOTICES.txt from the bundled
//     dependencies' license texts.
//
// Usage: node scripts/build-desktop.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = join(ROOT, "src", "plugin.tsx");
const OUT = join(ROOT, "desktop", "plugin.js");
const NOTICES = join(ROOT, "desktop", "THIRD_PARTY_NOTICES.txt");

const ALLOWED_EXTERNALS = ["@hermes/plugin-sdk", "react", "react/jsx-runtime"];
const SIZE_GATE_BYTES = 8 * 1024 * 1024; // 8 MiB — hard CI gate
const SIZE_TARGET_BYTES = Math.round(3.5 * 1024 * 1024); // 3.5 MiB — target

function mib(bytes) {
  return (bytes / (1024 * 1024)).toFixed(2);
}

function writeNotices() {
  // Bundled runtime dependencies only. react / react/jsx-runtime /
  // @hermes/plugin-sdk are external (provided by the Desktop host) and are
  // not shipped in the bundle, so they are not listed here.
  const threeLicense = readFileSync(join(ROOT, "node_modules", "three", "LICENSE"), "utf8").trimEnd();
  const threePkg = JSON.parse(readFileSync(join(ROOT, "node_modules", "three", "package.json"), "utf8"));
  const bvhLicense = readFileSync(join(ROOT, "node_modules", "three-mesh-bvh", "LICENSE"), "utf8").trimEnd();
  const otLicense = readFileSync(join(ROOT, "node_modules", "opentype.js", "LICENSE"), "utf8").trimEnd();
  const otPkg = JSON.parse(readFileSync(join(ROOT, "node_modules", "opentype.js", "package.json"), "utf8"));
  const cannonLicense = readFileSync(join(ROOT, "node_modules", "cannon-es", "LICENSE"), "utf8").trimEnd();
  const cannonPkg = JSON.parse(readFileSync(join(ROOT, "node_modules", "cannon-es", "package.json"), "utf8"));
  const interLicense = readFileSync(join(ROOT, "src", "assets", "OFL-Inter.txt"), "utf8").trimEnd();
  const bvhPkg = JSON.parse(readFileSync(join(ROOT, "node_modules", "three-mesh-bvh", "package.json"), "utf8"));
  const text = [
    "Plastis3D — Third-Party Notices",
    "three-gpu-pathtracer@0.0.24 — MIT License",
    readFileSync(join(ROOT, "node_modules", "three-gpu-pathtracer", "LICENSE"), "utf8").trimEnd(),
    "xatlas-web is not bundled; its optional UVUnwrapper is unused.",
    "=================================",
    "",
    "Generated by scripts/build-desktop.mjs. Lists the third-party code",
    "bundled into desktop/plugin.js. The Desktop host provides react,",
    "react/jsx-runtime, and @hermes/plugin-sdk; they are not bundled and",
    "are not listed here.",
    "",
    "---",
    "",
    `three.js (three@${threePkg.version}) — MIT License`,
    "",
    threeLicense,
    "",
    "---",
    "",
    `three-mesh-bvh (three-mesh-bvh@${bvhPkg.version}) — MIT License`,
    "",
    bvhLicense,
    "",
    "---",
    "",
    `opentype.js (opentype.js@${otPkg.version}) — MIT License`,
    "",
    otLicense,
    "",
    "---",
    "",
    `cannon-es (cannon-es@${cannonPkg.version}) — MIT License`,
    "",
    cannonLicense,
    "",
    "---",
    "",
    "Inter Regular, subset to Latin-1 (the bundled font bundled-sans-v1) — SIL Open Font License 1.1",
    "",
    interLicense,
    "",
  ].join("\n");
  writeFileSync(NOTICES, text, "utf8");
}

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: false,
  sourcemap: false,
  jsx: "automatic",
  external: ALLOWED_EXTERNALS,
  outfile: OUT,
  logLevel: "warning",
});

if (result.errors.length > 0) {
  for (const err of result.errors) console.error(err.text);
  process.exit(1);
}

const outSource = readFileSync(OUT, "utf8").replace(/^[ \t]+$/gm, "").replace(/ +\t/g, "\t");
writeFileSync(OUT, outSource);
if (outSource.includes("react/jsx-dev-runtime")) {
  console.error("BUILD FAILED: desktop/plugin.js references react/jsx-dev-runtime.");
  console.error("The build must use the automatic PRODUCTION JSX runtime only.");
  process.exit(1);
}

writeNotices();

const size = statSync(OUT).size;
console.log(`desktop/plugin.js: ${size} bytes (${mib(size)} MiB)`);
if (size > SIZE_GATE_BYTES) {
  console.error(`BUILD FAILED: bundle exceeds the 8 MiB CI gate (${mib(size)} MiB).`);
  process.exit(1);
}
if (size > SIZE_TARGET_BYTES) {
  console.warn(`WARNING: bundle is above the 3.5 MiB target (${mib(size)} MiB) — not a gate.`);
} else {
  console.log("Bundle is under the 3.5 MiB target.");
}
console.log("desktop/THIRD_PARTY_NOTICES.txt regenerated.");
